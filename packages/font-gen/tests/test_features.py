DIGEST = "000000000000"


def _fea(plan, cycle_mode="stream"):
    hm = {n: (500, 50) for n in plan.names()}
    return generate_features(plan, ligature_carets(plan, hm), digest12=DIGEST, cycle_mode=cycle_mode)


def _plan_from_spec(tmp_path, spec, **kw):
    store = synth_store(tmp_path / "s", spec, seed=1, rasters=False)
    plan, _ = plan_glyphs(load_store(store), **kw)
    store.close()
    return plan


def _class(text, name):
    m = re.search(rf"^@{re.escape(name)} = \[(.*?)\];$", text, re.M)
    return m.group(1).split() if m else None


def _gsub_indices(font_bytes):
    tt = TTFont(io.BytesIO(font_bytes))
    gsub = tt["GSUB"].table
    feats = {}
    for rec in gsub.FeatureList.FeatureRecord:
        feats.setdefault(rec.FeatureTag, rec.Feature.LookupListIndex)
    scripts = {s.ScriptTag: [gsub.FeatureList.FeatureRecord[i].FeatureTag for i in s.Script.DefaultLangSys.FeatureIndex] for s in gsub.ScriptList.ScriptRecord}
    return feats, scripts


def test_golden_fea_for_fixture_plan(fixture_plan, goldens, update_goldens):
    text = _fea(fixture_plan)
    assert text.startswith("# Generated by font-gen 0.1.0 from store 000000000000")
    assert_golden(goldens / "fixture.fea", text, update_goldens)
    assert _fea(fixture_plan) == text   # deterministic


def test_classes_letter_completeness_state_modulus_and_transparent(fixture_plan):
    text = _fea(fixture_plan)
    letters = set(_class(text, "LETTER"))
    assert letters == set(fixture_plan.letters) and {"a.fina.alt2", "f_i.alt3", "Q"} <= letters and "space" not in letters
    st = state_classes(fixture_plan)
    assert len(st) == 7 and "z" in st[0] and "z.alt1" in st[1] and "z" in st[2] and "z.alt1" in st[3] and "z" in st[6]
    assert all("Q" not in c for c in st) and "Q" in _class(text, "TRANSPARENT") and "space" in _class(text, "TRANSPARENT")
    assert _class(text, "ST3") == st[3] and _class(text, "BASE")[:3] == ["Q", "a", "f"]


def test_ligature_rule_shapes_for_allowed_subsets():
    C, L = ("e", "f", "t"), "e_f_t"
    assert ligature_rules(C, L, frozenset({"init", "medi", "fina", "isol"})) == ["sub e' f' t' by e_f_t;"]
    assert ligature_rules(C, L, frozenset({"medi", "fina"})) == [
        "sub @LETTER e' f' t' @LETTER by e_f_t;", "sub @LETTER e' f' t' by e_f_t;", "ignore sub e' f' t' @LETTER;"]
    assert ligature_rules(C, L, frozenset({"fina"})) == [
        "ignore sub @LETTER e' f' t' @LETTER;", "sub @LETTER e' f' t' by e_f_t;", "ignore sub e' f' t' @LETTER;"]
    assert ligature_rules(C, L, frozenset({"init"})) == [
        "ignore sub @LETTER e' f' t' @LETTER;", "ignore sub @LETTER e' f' t';", "sub e' f' t' @LETTER by e_f_t;"]
    assert ligature_rules(C, L, frozenset({"isol"})) == [
        "ignore sub @LETTER e' f' t' @LETTER;", "ignore sub @LETTER e' f' t';", "ignore sub e' f' t' @LETTER;", "sub e' f' t' by e_f_t;"]


def test_tiers_shared_lookup_then_restricted_in_own_lookups(tmp_path):
    plan = _plan_from_spec(tmp_path, {"f": {"medi": 3}, "i": {"medi": 3}, "l": {"medi": 3}, "s": {"medi": 3}, "t": {"medi": 3},
                                      "fi": {"init": 1, "medi": 1, "fina": 1, "isol": 1}, "fl": {"init": 1, "medi": 1, "fina": 1, "isol": 1},
                                      "ff": {"fina": 3}, "ffi": {"init": 1, "medi": 1, "fina": 1, "isol": 1}, "st": {"fina": 3}})
    names = [n for n, _ in ligature_lookups(plan)]
    assert names == ["LIGA_3", "LIGA_2", "LIGA_2_f_f", "LIGA_2_s_t"]
    rules = dict(ligature_lookups(plan))
    assert rules["LIGA_3"] == ["sub f' f' i' by f_f_i;"] and rules["LIGA_2"] == ["sub f' i' by f_i;", "sub f' l' by f_l;"]
    assert rules["LIGA_2_f_f"] == ["ignore sub @LETTER f' f' @LETTER;", "sub @LETTER f' f' by f_f;", "ignore sub f' f' @LETTER;"]
    text = _fea(plan)
    assert text.index("lookup LIGA_3 {") < text.index("lookup LIGA_2 {") < text.index("lookup LIGA_2_f_f {") < text.index("lookup LIGA_2_s_t {")
    assert "feature liga {" in text and "feature clig {" in text and text.count("lookup LIGA_2_f_f;") == 2
    build_stub_font(plan, text)


def test_positional_lookup_guards_keep_the_four_contexts_disjoint(fixture_plan, tmp_path):
    # the fixture has only a final ring for a: TO_FINA exists, the other three contexts are guarded by ignore rows
    assert positional_lookups(fixture_plan) == [
        ("TO_FINA", ["sub a by a.fina;"]),
        ("POS", ["ignore sub @LETTER @BASE' @LETTER;", "sub @LETTER @BASE' lookup TO_FINA;", "ignore sub @BASE' @LETTER;"]),
    ]
    plan = _plan_from_spec(tmp_path, {"a": {"medi": 3, "init": 3, "fina": 3, "isol": 3}, "b": {"medi": 3}})
    # medi is the default position whenever it reaches pos_min, so a TO_MEDI ring never arises and the medial row is always the guard
    assert dict(positional_lookups(plan))["POS"] == [
        "ignore sub @LETTER @BASE' @LETTER;", "sub @LETTER @BASE' lookup TO_FINA;",
        "sub @BASE' lookup TO_INIT @LETTER;", "sub @BASE' lookup TO_ISOL;"]
    assert [n for n, _ in positional_lookups(plan)] == ["TO_FINA", "TO_INIT", "TO_ISOL", "POS"]


def test_empty_lookups_are_omitted_with_their_rules_and_still_compile(tmp_path):
    no_pos = _plan_from_spec(tmp_path / "a", {"a": {"medi": 3}, "b": {"medi": 3}})
    text = _fea(no_pos)
    assert positional_lookups(no_pos) == [] and "TO_" not in text and "lookup POS" not in text and "ignore sub @LETTER @BASE'" not in text
    assert "lookup CYCLE;" in text and "lookup POS;" not in text
    build_stub_font(no_pos, text)
    small = _plan_from_spec(tmp_path / "b", {"a": {"medi": 2}, "b": {"medi": 2}})
    text2 = _fea(small)
    assert "lookup STEP1 {" in text2 and "lookup STEP2 {" not in text2 and "lookup STEP2;" not in text2
    assert _class(text2, "ST6") is not None
    build_stub_font(small, text2)
    singles = _plan_from_spec(tmp_path / "c", {"a": {"medi": 1}, "b": {"medi": 1}})
    text3 = _fea(singles)
    assert cycle_lookups(singles, "stream") == [] and "feature calt" not in text3 and "@ST0" not in text3
    assert "feature aalt" not in text3 and "table GDEF" in text3
    build_stub_font(singles, text3)


def test_compiled_lookup_order_and_scripts(fixture_plan):
    font = build_stub_font(fixture_plan, _fea(fixture_plan))
    feats, scripts = _gsub_indices(font)
    assert feats["liga"] == feats["clig"] and max(feats["liga"]) < min(feats["calt"])
    assert feats["calt"] == sorted(feats["calt"]) and len(feats["calt"]) == 2       # POS then CYCLE
    assert {"liga", "clig", "calt", "aalt"} <= set(scripts["DFLT"]) and {"liga", "clig", "calt", "aalt"} <= set(scripts["latn"])


def test_ring_5_classes_and_steps(fixture_loaded):
    plan, _ = plan_glyphs(fixture_loaded, ring_n=5)
    text = _fea(plan)
    assert all(_class(text, f"ST{k}") is not None for k in range(5)) and _class(text, "ST5") is None
    assert all(f"lookup STEP{k} {{" in text for k in (1, 2, 3, 4)) and "lookup STEP5" not in text


def test_cycle_mode_word_drops_transparent_rules(fixture_plan):
    text = _fea(fixture_plan, cycle_mode="word")
    cycle = text[text.index("lookup CYCLE {"):text.index("} CYCLE;")]
    assert "@TRANSPARENT" not in cycle and cycle.count("lookup STEP1;") == 1
    stream = _fea(fixture_plan)
    assert stream[stream.index("lookup CYCLE {"):stream.index("} CYCLE;")].count("lookup STEP1;") == 3


def test_ligature_overlaps_and_missing_component(fixture_plan, tmp_path):
    overlaps = ligature_overlaps(fixture_plan)
    assert [tuple(f.data["pair"]) for f in overlaps] == [("ff", "fi"), ("fi", "ing"), ("st", "tion")]   # sorted pairs, sorted list
    words = {tuple(f.data["pair"]): f.data["word"] for f in overlaps}
    assert words == {("ff", "fi"): "ffi", ("fi", "ing"): "fing", ("st", "tion"): "stion"}
    assert all(f.data["expect"] == list(resolve_ligatures(fixture_plan, f.data["word"])) for f in overlaps)
    # HarfBuzz-verified resolutions on the fixture plan (all five ligatures restricted: ff/ing/tion/st final-only, fi medial-only)
    assert resolve_ligatures(fixture_plan, "ffi") == ("f", "f", "i")          # ff's initial-context ignore consumes both f's, fi is then final
    assert resolve_ligatures(fixture_plan, "fing") == ("f", "i_n_g")          # longer tier first
    assert resolve_ligatures(fixture_plan, "stion") == ("s", "t_i_o_n")
    assert resolve_ligatures(fixture_plan, "zfiz") == ("z", "f_i", "z") and resolve_ligatures(fixture_plan, "fi") == ("f", "i")
    plan = _plan_from_spec(tmp_path, {"i": {"medi": 3}, "fi": {"medi": 2}})
    text = _fea(plan)
    assert "f_i" in plan.names() and "by f_i;" not in text
    build_stub_font(plan, text)


def test_gdef_classes_and_carets(fixture_plan):
    text = _fea(fixture_plan)
    gdef = text[text.index("table GDEF {"):]
    assert "LigatureCaretByPos f_i " in gdef and "LigatureCaretByPos t_i_o_n " in gdef
    classdef = re.search(r"GlyphClassDef \[(.*?)\], \[(.*?)\], , ;", gdef, re.S)
    bases, ligs = classdef.group(1).split(), classdef.group(2).split()
    assert "space" in bases and "a.fina.alt1" in bases and ".notdef" not in bases
    assert "f_i.alt3" in ligs and "t_i_o_n" in ligs and not set(bases) & set(ligs)
